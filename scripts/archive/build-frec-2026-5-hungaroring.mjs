function practiceRows(list) {
  return list.map(([num, laps, time, gap, kph], i) => [
    String(i + 1), String(num), NAMES[num], TEAMS[num], String(laps), time, gap, kph,
  ]);
}

function qualRows(list, dsq) {
  const rows = list.map(([num, laps, time, gap, kph], i) => [
    String(i + 1), String(num), NAMES[num], TEAMS[num], String(laps), time, gap, kph,
  ]);
  if (dsq?.length) {
    for (const [num, laps, time] of dsq) {
      rows.push(['DSQ', String(num), NAMES[num], TEAMS[num], String(laps), time, '—', '—']);
    }
  }
  return rows;
}

function gridIndex(grid, num) {
  const i = grid.indexOf(num);
  return i >= 0 ? i + 1 : null;
}

function raceRows(results, nc, grid, opts) {
  const rows = results.map(([num, laps, total, gap, best, kph], i) => {
    const fin = i + 1;
    const st = gridIndex(grid, num);
    const pole = st === 1;
    const fl = opts.fl != null && num === opts.fl;
    return [
      finSt(fin, st || fin), String(num), NAMES[num], TEAMS[num], String(laps), total, gap, best, kph,
      ptsForRace(opts.raceKey, num, fin, pole, fl),
    ];
  });
  for (const [num, laps, total, gap, best, kph] of nc) {
    const st = gridIndex(grid, num);
    rows.push([
      finSt('NC', st || '—'), String(num), NAMES[num], TEAMS[num], String(laps), total, gap, best, kph, '0',
    ]);
  }
  return rows;
}

