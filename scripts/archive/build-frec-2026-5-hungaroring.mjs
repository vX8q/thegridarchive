function finSt(fin, st) {
  if (fin === 'NC' || fin === 'RET' || fin === 'DNF') return `${fin} / ST ${st}`;
  const delta = st - fin;
  if (delta === 0) return `${fin} / ST ${st} —`;
  const arrow = delta > 0 ? `▲${delta}` : `▼${Math.abs(delta)}`;
  return `${fin} / ST ${st} ${arrow}`;
}

function mainPts(pos, pole, fl) {
  const table = [25, 18, 15, 12, 10, 8, 6, 4, 2, 1];
  let pts = pos >= 1 && pos <= 10 ? table[pos - 1] : 0;
  if (pole && pos >= 1) pts += 2;
  if (fl && pos >= 1 && pos <= 10) pts += 1;
  return String(pts);
}

